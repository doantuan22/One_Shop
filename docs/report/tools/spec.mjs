// --- helpers for the cart flow (adds one product for the screenshot, removed again afterwards) ---
let cartItemId = null;
async function addToCart(page) {
  await page.navigate('/products/1');
  await page.eval(`document.querySelector('#main-cart-form button[type=submit]')?.click()`);
  await page.waitFor(`location.pathname === '/cart'`, 'cart redirect');
  await sleep(300);
  cartItemId = await page.eval(`(document.querySelector('input[name=cartItemIds]') || {}).value || null`);
}
async function removeFromCart(page) {
  await page.navigate('/cart');
  await sleep(300);
  // the delete form of the (only) line
  await page.eval(`(() => { const f = [...document.querySelectorAll('form')].find(x => /\\/delete$/.test(x.getAttribute('action') || '')); if (f) f.submit(); })()`);
  await sleep(800);
}

